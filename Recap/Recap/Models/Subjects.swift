    /// 把 AI 回答的科目名稱對應回來
    static func match(_ text: String) -> SchoolSubject? {
        let t = text.trimmingCharacters(in: .whitespaces)
        guard !t.isEmpty else { return nil }
        if t.contains("講座") || t.contains("演講") { return .seminar }
        if t.contains("地科") || t.contains("地球") { return .earth }
        if t.contains("公民") { return .civics }
        return allCases.first { $0 != .general && $0 != .seminar && t.contains($0.title) }
    }

